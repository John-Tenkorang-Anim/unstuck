"""Persistence boundary for the transactional entry workflows.

Services own validation and state transitions. Transactions own locking, storage,
and atomic outbox writes. No database connection or SQL escapes this boundary.
"""
from __future__ import annotations

from contextlib import AbstractAsyncContextManager
from dataclasses import dataclass
from datetime import datetime
from hashlib import sha256
import json
from typing import Protocol
from uuid import UUID

from domain.models import CommentView, EntryView, OutcomeReportCreate, PersonRef, TopicRef
from domain.pagination import SearchPosition
from domain.actor import Account


def request_digest(payload: dict) -> bytes:
    return sha256(json.dumps(payload, sort_keys=True, separators=(',', ':'),
                             ensure_ascii=False, allow_nan=False).encode()).digest()


@dataclass
class EntryRecord:
    view: EntryView
    author_id: UUID
    last_activity: datetime | None = None


class CoreTransaction(Protocol):
    async def check_actor(self, actor: Account) -> Account: ...
    async def load_entry(self, entry_id: UUID, actor: Account | None = None,
                         *, own: bool = False, lock: bool = False) -> EntryRecord: ...
    async def insert_entry(self, entry: EntryView, author_id: UUID) -> None: ...
    async def save_entry(self, entry: EntryView, *, content: bool = False) -> None: ...
    async def snapshot(self, entry: EntryView) -> None: ...
    async def history(self, entry_id: UUID, *, owner: bool) -> list[EntryView]: ...
    async def event(self, entity: str, entity_id: UUID, previous: str | None,
                    destination: str, actor: Account | None = None, note: str | None = None) -> None: ...
    async def emit(self, entry: EntryView) -> None: ...
    async def replay(self, account_id: UUID, operation: str, key: str, payload: dict) -> dict | None: ...
    async def remember(self, account_id: UUID, operation: str, key: str, response: dict) -> None: ...
    async def person_ref(self, entry_id: UUID, account_id: UUID) -> PersonRef: ...
    async def topic_refs(self, slugs: list[str], lang: str) -> list[TopicRef]: ...
    async def get_report(self, entry_id: UUID, account_id: UUID) -> OutcomeReportCreate | None: ...
    async def put_report(self, entry_id: UUID, account_id: UUID, data: OutcomeReportCreate) -> None: ...
    async def reports_for(self, entry_id: UUID) -> list[OutcomeReportCreate]: ...
    async def get_signal(self, entry_id: UUID, account_id: UUID) -> str | None: ...
    async def put_signal(self, entry_id: UUID, account_id: UUID, kind: str, note: str | None) -> None: ...
    async def impact(self, author_id: UUID) -> tuple[int, dict[str, int]]: ...
    async def get_comment(self, comment_id: UUID) -> dict | None: ...
    async def insert_comment(self, record: dict) -> None: ...
    async def comments_for(self, entry_id: UUID) -> list[CommentView]: ...
    async def touch(self, entry_id: UUID, at: datetime) -> None: ...
    async def put_resolution(self, entry_id: UUID, by: str | None, target_id: UUID | None) -> None: ...
    async def stale_entries(self, before: datetime, limit: int) -> list[EntryRecord]: ...
    async def lock_graph(self) -> None: ...
    async def lock_entries(self, entry_ids: list[UUID]) -> None: ...
    async def put_link(self, from_id: UUID, to_id: UUID, rel: str,
                       actor_id: UUID, note: str | None) -> None: ...
    async def search(self, terms: list[str], filters: dict, viewer_ctx: dict,
                     after: SearchPosition | None, limit: int) -> tuple[list[EntryView], SearchPosition | None]: ...


class CoreRepository(Protocol):
    supports_extended_workflows: bool
    def transaction(self, *, readonly: bool = False) -> AbstractAsyncContextManager[CoreTransaction]: ...
    async def session_actor(self, token: str | None) -> Account | None: ...
    async def open(self) -> None: ...
    async def close(self) -> None: ...
    async def ready(self) -> bool: ...
